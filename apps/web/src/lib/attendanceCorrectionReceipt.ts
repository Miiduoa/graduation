import { doc, getDocFromServer } from 'firebase/firestore';
import { getAuth, getDb, isFirebaseConfigured } from './firebase';
import { loadCorrectionReview, type CorrectionReview } from './attendanceCorrectionReview';
import type { CorrectionBookmark } from './attendanceCorrectionBookmark';
import type { AttendanceCorrectionStatus } from './courseAttendance';

export type SavedCorrectionReceipt = {
  kind: 'saved';
  status: AttendanceCorrectionStatus;
  savedAt: string;
  current: CorrectionReview | null;
  changedSinceSave: boolean | null;
};
export type CorrectionReceiptResult = SavedCorrectionReceipt | { kind: 'not-found' };
const statuses = ['present', 'late', 'absent', 'excused'];
const failure = (code: string) => Object.assign(new Error('無法核對原更正收據'), { code: `functions/${code}` });

function savedTimestamp(value: unknown): string | null {
  try {
    const stamp = value as { toDate?: () => Date } | null;
    const date = typeof stamp?.toDate === 'function' ? stamp.toDate()
      : value instanceof Date ? value : typeof value === 'string' ? new Date(value) : null;
    return date && Number.isFinite(date.getTime()) ? date.toISOString() : null;
  } catch { return null; }
}

/** Read-only recovery. This function cannot invoke the correction mutation. */
export async function loadSavedCorrectionReceipt(bookmark: CorrectionBookmark): Promise<CorrectionReceiptResult> {
  const { actorUid, courseId, sessionId, requestId } = bookmark;
  if (![actorUid, courseId, sessionId, requestId].every((value) => typeof value === 'string' && /^[A-Za-z0-9_-]{1,128}$/.test(value))) {
    throw failure('invalid-argument');
  }
  const ensureActor = () => {
    if (!isFirebaseConfigured() || getAuth()?.currentUser?.uid !== actorUid) throw failure('unauthenticated');
  };
  let expired = false;
  const assertCurrent = () => { ensureActor(); if (expired) throw failure('unavailable'); };
  let timer: ReturnType<typeof setTimeout> | undefined;
  const read = async (): Promise<CorrectionReceiptResult> => {
    assertCurrent();
    const db = getDb();
    const teacher = await getDocFromServer(doc(db, 'groups', courseId, 'members', actorUid));
    assertCurrent();
    if (teacher.metadata.fromCache || teacher.metadata.hasPendingWrites || !teacher.exists() ||
        teacher.data().status !== 'active' || !['owner', 'instructor'].includes(teacher.data().role)) {
      throw failure('permission-denied');
    }
    // This matches the immutable audit ID generated by both server handlers.
    const bytes = new TextEncoder().encode(JSON.stringify([courseId, sessionId, actorUid, requestId]));
    const digest = await crypto.subtle.digest('SHA-256', bytes);
    assertCurrent();
    const id = 'correction_' + Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, '0')).join('');
    const receipt = await getDocFromServer(doc(db, 'groups', courseId, 'attendanceSessions', sessionId, 'attendanceCorrections', id));
    assertCurrent();
    if (receipt.metadata.fromCache || receipt.metadata.hasPendingWrites) throw failure('unavailable');
    if (!receipt.exists()) return { kind: 'not-found' };
    const record = receipt.data();
    const savedAt = savedTimestamp(record.correctedAt);
    if (record.teacherUid !== actorUid || record.groupId !== courseId || record.sessionId !== sessionId ||
        record.requestId !== requestId || typeof record.studentUid !== 'string' ||
        !/^[A-Za-z0-9_-]{1,128}$/.test(record.studentUid) ||
        typeof record.nextStatus !== 'string' || !statuses.includes(record.nextStatus) || !savedAt ||
        // Audit writes `revision` (not `nextRevision`); match both JS and TS handlers.
        (record.revision !== undefined && (typeof record.revision !== 'number' ||
          !Number.isSafeInteger(record.revision) || record.revision < 1))) {
      throw failure('failed-precondition');
    }
    let current: CorrectionReview | null = null;
    try { current = await loadCorrectionReview(courseId, sessionId, record.studentUid); }
    catch { /* The saved audit can be proven even when the current record cannot. */ }
    assertCurrent();
    return {
      kind: 'saved', status: record.nextStatus as AttendanceCorrectionStatus, savedAt, current,
      changedSinceSave: current === null ? null : typeof record.revision === 'number'
        ? current.revision !== record.revision : current.row.status !== record.nextStatus,
    };
  };
  try {
    return await Promise.race([
      read(),
      new Promise<never>((_resolve, reject) => {
        timer = setTimeout(() => { expired = true; reject(failure('unavailable')); }, 15_000);
      }),
    ]);
  } finally { if (timer !== undefined) clearTimeout(timer); }
}
