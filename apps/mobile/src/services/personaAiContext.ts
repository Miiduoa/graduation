/**
 * Persona AI Context — 為每個 demo 角色生成「AI 助理應該知道的身份背景」
 *
 * 為什麼需要：
 *   AI 助理的 system prompt 預設只組學生視角（我的課/作業）。當 demo 切到教師/管理員
 *   /店家等角色時，AI 不知道自己面對的是誰，常常會回「我沒有資料」或答非所問。
 *
 *   這個模組依 demo uid 注入一段「角色背景 + 預設可回答的 demo 問題清單」，
 *   讓 AI 在 demo 期間對任何角色都能合理回答。
 *
 * 使用方式：
 *   ai.ts buildSystemPrompt 內呼叫 getDemoPersonaPromptAddon(context.userId)
 *   若不是 demo uid，回空字串，不影響真實使用者。
 */

